"""Run a biTrader strategy on the Freqtrade engine.

biTrader strategies implement ``Strategy.generate(df, params) -> target``;
Freqtrade strategies implement ``IStrategy.populate_entry_trend`` etc. This
module bridges the two: it renders a throwaway ``IStrategy`` subclass into the
sidecar's ``user_data/strategies`` folder that imports the local plugin by
module name (built-ins) or by file path (user plugins) and turns the ``target``
column into entry/exit signals.

Freqtrade's own ROI and stoploss are switched off in the adapter, because the
target column already decides when to be in and out. Leaving them on would make
the same strategy produce two different result sets and the comparison useless.

The adapter is regenerated on every backtest: it is a build artifact, not a
file the user maintains, and it is prefixed ``Btrader_`` so the Freqtrade
strategy list can tell the two families apart.
"""

from __future__ import annotations

import uuid
from pathlib import Path
from typing import Any

import pandas as pd

from .freqtrade import FreqtradeError

ADAPTER_PREFIX = "Btrader_"

SIGNAL_COLUMNS = ("enter_long", "exit_long", "enter_short", "exit_short")


def adapter_class_name(key: str) -> str:
    """Freqtrade resolves ``--strategy`` by class name, and the bridge checks
    for ``<name>.py`` first — so the class name *is* the file name."""
    stem = "".join(ch for ch in key if ch.isalnum() or ch == "_") or "strategy"
    return f"{ADAPTER_PREFIX}{stem}"


def target_to_signals(dataframe: pd.DataFrame, column: str = "bt_target") -> pd.DataFrame:
    """Turn a per-bar target into Freqtrade entry/exit columns.

    1.0 long, 0.0 flat, -1.0 short — evaluated on the close, exactly like the
    in-process engine. Signals fire on the *change* of target: staying long is
    one entry, not one per bar.
    """
    if column not in dataframe.columns:
        for name in SIGNAL_COLUMNS:
            dataframe[name] = 0
        return dataframe
    target = dataframe[column].astype(float).fillna(0.0)
    previous = target.shift(1).fillna(0.0)
    for name in SIGNAL_COLUMNS:
        dataframe[name] = 0
    if len(dataframe):
        dataframe.loc[(target > 0) & (previous <= 0), "enter_long"] = 1
        dataframe.loc[(target <= 0) & (previous > 0), "exit_long"] = 1
        dataframe.loc[(target < 0) & (previous >= 0), "enter_short"] = 1
        dataframe.loc[(target >= 0) & (previous < 0), "exit_short"] = 1
    return dataframe


_TEMPLATE = '''"""Auto-generated by biTrader: a local strategy on Freqtrade.

Regenerated on every backtest — edits are lost, and the file is safe to delete.
"""

from __future__ import annotations

import importlib
import importlib.util
import sys

_PROJECT_SRC = %(project_src)r
if _PROJECT_SRC and _PROJECT_SRC not in sys.path:
    sys.path.insert(0, _PROJECT_SRC)

import pandas as pd  # noqa: F401  (strategies expect pandas semantics)
from freqtrade.strategy import IStrategy

from btrader.freqtrade_compat import target_to_signals
from btrader.strategy.base import Strategy

_KEY = %(key)r
_PARAMS = %(params)s
_LOAD = %(load)s


def _load_strategy():
    """Import the biTrader plugin this adapter stands for."""
    if _LOAD["kind"] == "file":
        spec = importlib.util.spec_from_file_location(_LOAD["module"], _LOAD["path"])
        if spec is None or spec.loader is None:
            raise RuntimeError("无法加载本地策略文件: " + _LOAD["path"])
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)
    else:
        module = importlib.import_module(_LOAD["module"])
    fallback = None
    for obj in vars(module).values():
        if not isinstance(obj, type) or not issubclass(obj, Strategy) or obj is Strategy:
            continue
        if getattr(obj, "key", "") == _KEY:
            return obj()
        if fallback is None:
            fallback = obj
    if fallback is not None:
        return fallback()
    raise RuntimeError("策略文件里没有 Strategy 子类: " + _LOAD["module"])


class %(cls)s(IStrategy):
    """biTrader strategy %(key)s driven through Freqtrade's backtester."""

    INTERFACE_VERSION = 3
    timeframe = %(timeframe)r
    startup_candle_count = %(startup)d
    # The target column already decides when to be in and out; leaving
    # Freqtrade's own ROI/stoploss on would make the two engines disagree.
    minimal_roi = {"0": 1000}
    stoploss = -0.99
    trailing_stop = False
    use_custom_stoploss = False
    use_exit_signal = True
    exit_profit_only = False
    ignore_roi_if_entry_signal = False
    process_only_new_candles = False
    can_short = %(can_short)s

    def populate_indicators(self, dataframe, metadata):
        strategy = _load_strategy()
        frame = dataframe.copy()
        if "timestamp" not in frame.columns:
            if "date" in frame.columns:
                frame["timestamp"] = frame["date"].astype("int64") // 10 ** 6
            else:
                frame["timestamp"] = 0
        produced = strategy.generate(frame, dict(_PARAMS))
        target = produced["target"] if "target" in produced.columns else None
        if target is None:
            dataframe["bt_target"] = 0.0
        else:
            dataframe["bt_target"] = (
                target.reindex(dataframe.index).fillna(0.0).astype(float)
            )
        return dataframe

    def populate_entry_trend(self, dataframe, metadata):
        return target_to_signals(dataframe)

    def populate_exit_trend(self, dataframe, metadata):
        return dataframe
'''


def render_adapter(
    *,
    key: str,
    class_name: str,
    project_src: str,
    params: dict[str, Any],
    load: dict[str, str],
    timeframe: str = "1h",
    startup: int = 60,
    can_short: bool = False,
) -> str:
    """Render the IStrategy shim for one local strategy."""
    return _TEMPLATE % {
        "key": key,
        "cls": class_name,
        "project_src": project_src,
        # ``repr`` — not JSON: this dict is pasted into Python source, and
        # JSON's ``true``/``false`` are a NameError there.
        "params": repr(dict(params)),
        "load": repr(dict(load)),
        "timeframe": timeframe,
        "startup": max(2, int(startup)),
        "can_short": "True" if can_short else "False",
    }


def ensure_adapter(
    bridge: Any,
    registry: Any,
    key: str,
    *,
    params: dict[str, Any] | None = None,
    timeframe: str = "1h",
    allow_short: bool | None = None,
    project_src: str = "",
) -> dict[str, Any]:
    """Write (or refresh) the adapter for ``key`` and return its identity."""
    try:
        strategy = registry.get(key)
    except KeyError as exc:
        raise FreqtradeError(f"未知的本地策略：{key}") from exc
    source = registry.source_path(key)
    if source is not None:
        load = {
            "kind": "file",
            "module": f"btrader_adapter_source_{key}",
            "path": str(Path(source).resolve()),
        }
    else:
        load = {"kind": "module", "module": type(strategy).__module__}
    if not project_src:
        from . import paths

        project_src = str(paths.project_root() / "src")
    cleaned = strategy.validate_params(dict(params or {}))
    # Both have to agree: the strategy must be willing to short, and the venue
    # (the caller says whether it is a futures market) must allow it.
    can_short = bool(strategy.meta.allow_short) and (
        bool(strategy.meta.allow_short) if allow_short is None else bool(allow_short)
    )
    class_name = adapter_class_name(key)
    code = render_adapter(
        key=key,
        class_name=class_name,
        project_src=project_src,
        params=cleaned,
        load=load,
        timeframe=timeframe,
        startup=max(20, int(strategy.meta.min_bars) + 20),
        can_short=can_short,
    )
    path = (Path(bridge.strategy_dir) / f"{class_name}.py").resolve()
    if path.parent != Path(bridge.strategy_dir).resolve():
        raise FreqtradeError("适配器路径越界")
    tmp = path.with_name(f".{path.name}.{uuid.uuid4().hex}.tmp")
    tmp.write_text(code, encoding="utf-8", newline="\n")
    tmp.replace(path)
    return {
        "name": class_name,
        "file": path.name,
        "path": str(path),
        "key": key,
        "params": cleaned,
    }


def remove_adapter(bridge: Any, key: str) -> bool:
    """Delete the adapter of a strategy (after a rename or a delete)."""
    path = Path(bridge.strategy_dir) / f"{adapter_class_name(key)}.py"
    if not path.exists():
        return False
    path.unlink()
    return True
